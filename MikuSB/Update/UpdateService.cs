using System.Diagnostics;
using System.Globalization;
using System.IO.Compression;
using System.Runtime.InteropServices;
using MikuSB.Internationalization;
using MikuSB.Net;
using MikuSB.Util;
using MikuSB.Util.Security;

namespace MikuSB.MikuSB.Update;

/// <summary>
///     What the panel shows about updates: the running build, the newest release and whether the two
///     differ. <see cref="Error" /> is set when the lookup itself failed, which is not the same as
///     "you are up to date".
/// </summary>
public sealed record UpdateCheck(
    string Current,
    string? Latest,
    bool Available,
    string? AssetName,
    long AssetSize,
    string? Notes,
    string? Error);

public static class UpdateService
{
    private static readonly Logger Logger = new("Updater");
    private static readonly bool UpdateEnabled = true;
    private static readonly bool AskBeforeUpdate = true;
    // Where self-updates come from: this fork's own releases, the only ones whose assets match what we ship.
    private static readonly string RepositoryOwner =
        Environment.GetEnvironmentVariable("MIKUSB_UPDATE_OWNER") ?? "SalmanTKhan";
    private static readonly string RepositoryName =
        Environment.GetEnvironmentVariable("MIKUSB_UPDATE_REPO") ?? "MikuSB";

    // Both forms resolve to the same file; raw.githubusercontent.com is the cheap one, the /raw/ path is
    // the fallback for the rare proxy that only understands github.com URLs.
    private static readonly string[] VersionFileUrls =
    [
        $"https://raw.githubusercontent.com/{RepositoryOwner}/{RepositoryName}/main/version.txt",
        $"https://github.com/{RepositoryOwner}/{RepositoryName}/raw/main/version.txt"
    ];
    private static readonly int ReleaseCheckTimeoutSeconds = 10;
    private static readonly int PackageDownloadTimeoutSeconds = 300;
    private static readonly int ResourceDownloadTimeoutSeconds = 300;
    private static readonly int ChecksumDownloadTimeoutSeconds = 30;
    private static readonly int CheckCacheSeconds = 300;
    private static readonly SemaphoreSlim CheckGate = new(1, 1);

    // This fork's own resource snapshot (shop/*.json regenerated by scripts/parse_shop_csv.py) is
    // served from here instead of the upstream Kei-Luna archive, whose shop_tab.json uses the old
    // schema (empty numeric strings, no nested Goods) and breaks ShopTabExcel on load.
    // Override with MIKUSB_RESOURCE_ARCHIVE to point at another snapshot without rebuilding.
    private static readonly string ResourceArchiveUrl =
        Environment.GetEnvironmentVariable("MIKUSB_RESOURCE_ARCHIVE")
        ?? "https://github.com/dubstream3/MikuSB-Resource/archive/refs/heads/main.zip";

    private static readonly string? ResourceArchiveSha256 =
        Environment.GetEnvironmentVariable("MIKUSB_RESOURCE_SHA256") is { Length: > 0 } pinned ? pinned.Trim() : null;

    private static readonly string[] RequiredResourceFiles =
    [
        "item/templates/card.json",
        "item/templates/weapon.json"
    ];

    // Bumped whenever the committed resource data changes (new goods rows, corrected tables,
    // added text keys). The updater used to only ask "do these two files exist", so a data fix
    // could never reach a deployment that already had a Resources tree - it kept running against
    // stale tables forever. The installed version is written next to the data and compared on
    // every start; a mismatch throws the whole tree away and downloads the package again.
    // 0.0.2: adds ui/replay/*.png - the DLC era key art the admin panel serves on its replay page.
    public const string ResourceDataVersion = "0.0.2";
    private const string ResourceVersionFileName = ".mikusb-resource-version";

    private static UpdateCheck _lastCheck = new(BuildVersion.Current, null, false, null, 0, null, null);
    private static long _lastCheckTicks;

    /// <summary>
    ///     Set by the host so an update triggered from the panel can shut the server down the same way
    ///     Ctrl+C does, after the updater has been started.
    /// </summary>
    public static Action<int>? ShutdownRequest { get; set; }

    /// <summary>Most recent lookup, for the panel. Never blocks.</summary>
    public static UpdateCheck LastCheck => _lastCheck;

    public static async Task<UpdateCheck> CheckAsync(bool force = false, CancellationToken cancellationToken = default)
    {
        if (!UpdateEnabled)
            return Remember(new UpdateCheck(BuildVersion.Current, null, false, null, 0, null, "update_disabled"));

        var age = Environment.TickCount64 - Interlocked.Read(ref _lastCheckTicks);
        if (!force && age < CheckCacheSeconds * 1000L)
            return _lastCheck;

        await CheckGate.WaitAsync(cancellationToken);
        try
        {
            age = Environment.TickCount64 - Interlocked.Read(ref _lastCheckTicks);
            if (!force && age < CheckCacheSeconds * 1000L)
                return _lastCheck;

            using var client = GitHubApi.CreateClient("MikuSB-Updater");
            var published = await ReadPublishedVersionAsync(client, cancellationToken);
            if (published == null)
                return Remember(new UpdateCheck(BuildVersion.Current, null, false, null, 0, null, "version_unavailable"));

            // Only a strictly newer version counts: version.txt may come through a mirror, and accepting
            // an older one would let it roll the server back to a build with known problems.
            var latest = BuildVersion.Normalize(published);
            var available = Version.TryParse(latest, out var latestVersion)
                            && Version.TryParse(BuildVersion.Current, out var currentVersion)
                            && latestVersion > currentVersion;
            var assetName = available ? AssetNameForCurrentPlatform() : null;

            return Remember(new UpdateCheck(
                BuildVersion.Current,
                latest,
                available,
                assetName,
                0,
                null,
                null));
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            throw;
        }
        catch (Exception ex)
        {
            Logger.Warn(I18NManager.Translate("Server.ServerInfo.AutoUpdateCheckFailed"), ex);
            return Remember(new UpdateCheck(BuildVersion.Current, null, false, null, 0, null, "check_failed"));
        }
        finally
        {
            CheckGate.Release();
        }
    }

    /// <summary>Startup path: check, ask on the console, then hand over to MikuSB.Updater.</summary>
    public static Task<bool> TryStartSelfUpdateAsync() => ApplyAsync(ask: true);

    /// <summary>
    ///     Panel path. There is nobody at the console to answer a prompt, so the confirmation is
    ///     implicit in the click that got here.
    /// </summary>
    public static Task<bool> ApplyFromPanelAsync() => ApplyAsync(ask: false);

    private static async Task<bool> ApplyAsync(bool ask)
    {
        if (!UpdateEnabled || Environment.GetEnvironmentVariable("MIKUSB_OFFLINE") == "1")
            return false;

        var updaterPath = Path.Combine(AppContext.BaseDirectory, "MikuSB.Updater.exe");
        if (!File.Exists(updaterPath))
        {
            Logger.Debug(I18NManager.Translate("Server.ServerInfo.AutoUpdateSkippedNoUpdater"));
            return false;
        }

        try
        {
            Logger.Info(I18NManager.Translate("Server.ServerInfo.CurrentBuildVersion", BuildVersion.Current));

            var check = await CheckAsync(force: true);
            if (check.Error != null || check.Latest == null)
                return false;

            if (!check.Available)
                return false;

            if (ask && AskBeforeUpdate && !ConfirmUpdate(check.Latest))
            {
                Logger.Info(I18NManager.Translate("Server.ServerInfo.SkippedUpdateByUser", check.Latest));
                return false;
            }

            // The panel is the only place that can show a long download, so the host publishes what it is
            // downloading; SdkServer reads it from Common state instead of a bridge delegate (delegates are
            // wired after the update check, and the panel is already serving while this runs).
            ServerRuntime.Enter(ServerRuntime.PhaseUpdate, check.Latest);

            using var client = GitHubApi.CreateClient("MikuSB-Updater");

            var tempRoot = CreateStagingDirectory();

            var assetName = check.AssetName ?? throw new InvalidDataException("Release asset name is unknown.");
            var packagePath = Path.Combine(tempRoot, assetName);
            Logger.Info(I18NManager.Translate("Server.ServerInfo.DownloadingUpdate", check.Latest));

            var packageUrl = PackageUrl(check.Latest, assetName);
            await DownloadAsync(client, packageUrl, packagePath, PackageDownloadTimeoutSeconds, allowMirrors: false);

            // Without a pinned hash the resource archive cannot be trusted, so the update leaves resources alone.
            var resourcePackagePath = "";
            if (ResourceArchiveSha256 != null)
            {
                resourcePackagePath = Path.Combine(tempRoot, "MikuSB-Resource-main.zip");
                Logger.Info(I18NManager.Translate("Server.ServerInfo.DownloadingResourcePackage"));
                await DownloadAsync(client, ResourceArchiveUrl, resourcePackagePath, ResourceDownloadTimeoutSeconds);
                VerifyResourceArchive(resourcePackagePath);
            }

            // Executable code: the package and its checksum come directly from GitHub, and an update
            // whose checksum is missing or wrong is abandoned before anything is installed.
            var checksumPath = Path.Combine(tempRoot, assetName + ".sha256");
            await DownloadAsync(client, packageUrl + ".sha256", checksumPath, ChecksumDownloadTimeoutSeconds, allowMirrors: false);
            VerifySha256(packagePath, checksumPath);

            // The signature is what proves the package is ours: GitHub only proves where it came from.
            var signaturePath = Path.Combine(tempRoot, assetName + ".sig");
            await DownloadAsync(client, packageUrl + ".sig", signaturePath, ChecksumDownloadTimeoutSeconds, allowMirrors: false);
            if (!ReleaseSignature.Verify(File.ReadAllBytes(packagePath), File.ReadAllText(signaturePath)))
                throw new InvalidDataException("Update package signature is not valid.");

            var stagedUpdaterPath = StageUpdaterExecutable();
            var process = Process.Start(new ProcessStartInfo
            {
                FileName = stagedUpdaterPath,
                UseShellExecute = false,
                WorkingDirectory = Path.GetDirectoryName(stagedUpdaterPath)!,
                ArgumentList =
                {
                    "--package", packagePath,
                    "--resource-package", resourcePackagePath,
                    "--target", AppContext.BaseDirectory,
                    "--resource-target", Path.Combine(AppContext.BaseDirectory, ConfigManager.Config.Path.ResourcePath),
                    "--restart", Path.Combine(AppContext.BaseDirectory, "MikuSB.exe"),
                    "--pid", Environment.ProcessId.ToString()
                }
            });

            if (process == null)
            {
                Logger.Warn(I18NManager.Translate("Server.ServerInfo.FailedToStartUpdater"));
                ServerRuntime.BackToRunning();
                return false;
            }

            Logger.Warn(I18NManager.Translate("Server.ServerInfo.UpdateHandedOver", check.Latest));
            // The startup path returns from Main and the process ends there; the panel path has no such exit,
            // so the host registers ShutdownRequest and we ask it to stop now that the updater holds the files.
            ShutdownRequest?.Invoke(0);
            // Only reachable when nobody is listening for the shutdown request (the console-only hosts): then
            // this process keeps running, so it must stop claiming it is still downloading.
            ServerRuntime.BackToRunning();
            return true;
        }
        catch (Exception ex)
        {
            ServerRuntime.BackToRunning();
            Logger.Warn(I18NManager.Translate("Server.ServerInfo.AutoUpdateCheckFailed"), ex);
            return false;
        }
    }

    public static async Task EnsureResourcesPresentAsync()
    {
        if (!AreRequiredResourcesPresent())
        {
            if (Environment.GetEnvironmentVariable("MIKUSB_OFFLINE") == "1")
                throw new FileNotFoundException("Local resources missing; configure Path.ResourcePath.");
            Logger.Warn(I18NManager.Translate("Server.ServerInfo.RequiredResourcesMissing"));
            try
            {
                await DownloadAndInstallResourcesAsync();
            }
            finally
            {
                // Registered as well when the download throws: a failed install leaves the host in the error
                // path, and the panel must not keep advertising a download that is no longer running.
                ServerRuntime.BackToRunning();
            }
        }
    }

    /// <summary>
    ///     Somewhere writable for the downloaded packages. %TEMP% is the natural home, but locked-down
    ///     machines (and sandboxes that deny writes under %TEMP%\MikuSB) make it fail, so fall back to a
    ///     plain temp directory and finally to the install directory itself.
    /// </summary>
    private static string CreateStagingDirectory(string leaf = "updates")
    {
        var name = Guid.NewGuid().ToString("N");
        var candidates = new[]
        {
            Path.Combine(Path.GetTempPath(), "MikuSB", leaf, name),
            Path.Combine(Path.GetTempPath(), "mikusb-" + leaf + "-" + name),
            Path.Combine(AppContext.BaseDirectory, "update-cache", leaf, name)
        };

        Exception? lastError = null;
        foreach (var candidate in candidates)
        {
            try
            {
                Directory.CreateDirectory(candidate);
                return candidate;
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                lastError = ex;
            }
        }

        throw new IOException("No writable directory for the update package.", lastError);
    }

    /// <summary>
    ///     One zip per platform, named after the RID the release job produced.
    /// </summary>
    private static string AssetNameForCurrentPlatform()
    {
        var platform = OperatingSystem.IsWindows()
            ? "win"
            : OperatingSystem.IsLinux()
                ? "linux"
                : OperatingSystem.IsMacOS()
                    ? "osx"
                    : "unknown";
        var architecture = RuntimeInformation.ProcessArchitecture switch
        {
            Architecture.Arm64 => "arm64",
            Architecture.X64 => "x64",
            Architecture.X86 => "x86",
            _ => "x64"
        };
        return $"MikuSB-{platform}-{architecture}.zip";
    }

    private static string PackageUrl(string version, string assetName) =>
        $"https://github.com/{RepositoryOwner}/{RepositoryName}/releases/download/v{version}/{assetName}";

    /// <summary>
    ///     version.txt from the branch the release job builds from. Reading the file (through the mirror
    ///     list) replaces the release API call: no rate limit, no token, and the answer is exactly the
    ///     version that package would install.
    /// </summary>
    private static async Task<string?> ReadPublishedVersionAsync(HttpClient client, CancellationToken cancellationToken)
    {
        foreach (var url in VersionFileUrls)
        {
            var text = await GitHubApi.ReadTextAsync(
                url,
                new GitHubDownloadOptions { TimeoutSeconds = ReleaseCheckTimeoutSeconds, HeaderTimeoutSeconds = 8 },
                client,
                cancellationToken);
            if (text != null)
                return ParseVersionText(text);
        }

        // One warning for the whole lookup instead of one debug line per dropped source: the per-source
        // lines are inside GitHubApi.ReadTextAsync and stay silent when a mirror answers.
        Logger.Warn($"version.txt could not be read from any source ({VersionFileUrls.Length} url(s) tried); " +
                    "the update check reports version_unavailable.");
        return null;
    }

    private static string? ParseVersionText(string text)
    {
        foreach (var line in text.Split('\n'))
        {
            var value = line.Trim();
            if (value.Length == 0 || value.StartsWith('#'))
                continue;

            // version.txt holds "v=6.2.0" (the release workflow reads the same line and strips "v="),
            // but a hand-edited file may hold "v6.2.0" or just "6.2.0".
            if (value.StartsWith("v=", StringComparison.OrdinalIgnoreCase))
                value = value[2..];
            else if (value.StartsWith("v", StringComparison.OrdinalIgnoreCase))
                value = value[1..];

            value = value.TrimStart('=').Trim();

            return value.Length == 0 ? null : value;
        }

        return null;
    }

    private static UpdateCheck Remember(UpdateCheck check)
    {
        _lastCheck = check;
        Interlocked.Exchange(ref _lastCheckTicks, Environment.TickCount64);
        return check;
    }

    private static string StageUpdaterExecutable()
    {
        var sourceDirectory = AppContext.BaseDirectory;
        var stagingDirectory = CreateStagingDirectory("updater");

        foreach (var sourcePath in Directory.EnumerateFiles(sourceDirectory, "MikuSB.Updater*", SearchOption.TopDirectoryOnly))
        {
            var destinationPath = Path.Combine(stagingDirectory, Path.GetFileName(sourcePath));
            File.Copy(sourcePath, destinationPath, overwrite: true);
        }

        var stagedUpdaterPath = Path.Combine(stagingDirectory, "MikuSB.Updater.exe");
        if (!File.Exists(stagedUpdaterPath))
            throw new FileNotFoundException("Failed to stage MikuSB.Updater.exe.", stagedUpdaterPath);

        return stagedUpdaterPath;
    }

    private static bool AreRequiredResourcesPresent()
    {
        var resourcePath = Path.Combine(AppContext.BaseDirectory, ConfigManager.Config.Path.ResourcePath);
        if (!Directory.Exists(resourcePath))
            return false;

        if (!RequiredResourceFiles.All(fileName => File.Exists(Path.Combine(resourcePath, fileName))))
            return false;

        // Only a tree this updater installed carries the marker. Anything else is a hand-managed resource
        // checkout (Path.ResourcePath) and must never be replaced, because a mismatch deletes the tree.
        var installed = ReadInstalledResourceVersion(resourcePath);
        return installed == null || installed == ResourceDataVersion;
    }

    private static string? ReadInstalledResourceVersion(string resourcePath)
    {
        var versionPath = Path.Combine(resourcePath, ResourceVersionFileName);
        if (!File.Exists(versionPath))
            return null;

        try
        {
            return File.ReadAllText(versionPath).Trim();
        }
        catch (IOException)
        {
            return null;
        }
    }

    private static void VerifyResourceArchive(string path)
    {
        var actual = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(path)));
        if (!string.Equals(actual, ResourceArchiveSha256, StringComparison.OrdinalIgnoreCase))
            throw new InvalidDataException("Downloaded resource archive does not match MIKUSB_RESOURCE_SHA256.");
    }

    private static async Task DownloadAndInstallResourcesAsync()
    {
        // Checked first, because the existing tree is removed below.
        if (ResourceArchiveSha256 == null)
            throw new InvalidOperationException(
                "Install resources by hand, or set MIKUSB_RESOURCE_SHA256 to the expected archive hash to download them.");

        // Same reason as the release download above: this runs inside startup, while the panel is already
        // serving, and it is the slowest step of a first run.
        ServerRuntime.Enter(ServerRuntime.PhaseResources, ResourceArchiveUrl);

        using var client = GitHubApi.CreateClient("MikuSB-Updater");
        var tempRoot = Path.Combine(Path.GetTempPath(), "MikuSB", "resources", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempRoot);

        var resourceTargetDirectory = Path.Combine(AppContext.BaseDirectory, ConfigManager.Config.Path.ResourcePath);

        // A version bump means the data on disk is stale, not broken: replace the tree wholesale so
        // rows that were removed upstream disappear as well. Installing over the top would keep them.
        if (Directory.Exists(resourceTargetDirectory))
        {
            var installedVersion = ReadInstalledResourceVersion(resourceTargetDirectory) ?? "unknown";
            Logger.Warn(I18NManager.Translate("Server.ServerInfo.ResourcesOutdated",
                installedVersion, ResourceDataVersion));
            Directory.Delete(resourceTargetDirectory, recursive: true);
        }

        var resourcePackagePath = Path.Combine(tempRoot, "MikuSB-Resource-main.zip");
        await DownloadAsync(client, ResourceArchiveUrl, resourcePackagePath, ResourceDownloadTimeoutSeconds);
        VerifyResourceArchive(resourcePackagePath);

        var installedFiles = InstallResourcesFromArchive(resourcePackagePath, resourceTargetDirectory);
        Logger.Info(I18NManager.Translate("Server.ServerInfo.ResourcesInstalled",
            installedFiles.ToString(), resourceTargetDirectory));
    }

    private static int InstallResourcesFromArchive(string resourcePackagePath, string resourceTargetDirectory)
    {
        Logger.Info(I18NManager.Translate("Server.ServerInfo.InstallingResources", resourceTargetDirectory));

        var resourceStagingDirectory = Path.Combine(Path.GetTempPath(), "MikuSB", "resource-staging", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(resourceStagingDirectory);

        ZipFile.ExtractToDirectory(resourcePackagePath, resourceStagingDirectory, overwriteFiles: true);

        var extractedRoot = Directory.GetDirectories(resourceStagingDirectory).FirstOrDefault() ?? resourceStagingDirectory;
        Directory.CreateDirectory(resourceTargetDirectory);
        var copiedFiles = CopyDirectory(extractedRoot, resourceTargetDirectory);
        File.WriteAllText(Path.Combine(resourceTargetDirectory, ResourceVersionFileName), ResourceDataVersion);
        return copiedFiles;
    }

    private static bool ConfirmUpdate(string latestVersion)
    {
        // Services and headless launches have no console to read a key from and would otherwise sit here
        // forever on a redirected stdin. Skipping the prompt means "no": the panel still offers the update.
        if (!string.IsNullOrEmpty(Environment.GetEnvironmentVariable("MIKUSB_NO_UPDATE_PROMPT")))
            return false;

        Console.Write(I18NManager.Translate("Server.ServerInfo.ConfirmUpdate",
            BuildVersion.Current, latestVersion));

        try
        {
            var key = Console.ReadKey(intercept: true);
            Console.WriteLine();
            return key.Key is ConsoleKey.Enter or ConsoleKey.Y;
        }
        catch
        {
            // No interactive console (redirected output, service, panel): beam the question into the
            // log and take the safe answer instead of pretending a key was pressed.
            Console.WriteLine();
            return false;
        }
    }

    /// <summary>
    ///     One download entry point for everything GitHub: mirrors, header budget, stall watchdog and
    ///     progress reporting all live in <see cref="GitHubApi" />, this only supplies the wording.
    /// </summary>
    private static Task DownloadAsync(HttpClient client, string url, string destinationPath, int timeoutSeconds, bool allowMirrors = true)
    {
        var fileName = Path.GetFileName(destinationPath);
        var mirrorCount = GitHubApi.Mirrors.Count;
        var lastReport = 0L;
        var stopwatch = Stopwatch.StartNew();
        var failedCounter = 0;

        var options = new GitHubDownloadOptions
        {
            TimeoutSeconds = timeoutSeconds,
            DirectAttempts = 1,
            AllowMirrors = allowMirrors,
            OnAttempt = (host, isMirror, index, total) =>
            {
                if (isMirror)
                    Logger.Info(I18NManager.Translate("Server.ServerInfo.DownloadSourceMirror",
                        (index).ToString(CultureInfo.InvariantCulture),
                        Math.Max(0, total - 1).ToString(CultureInfo.InvariantCulture), host));
                else
                    Logger.Info(I18NManager.Translate("Server.ServerInfo.DownloadSourceDirect", host));
                stopwatch.Restart();
                lastReport = 0;
            },
            OnProgress = (host, bytes, total) =>
            {
                var now = Environment.TickCount64;
                if (bytes > 0 && now - lastReport < 2000)
                    return;
                lastReport = now;

                var seconds = stopwatch.Elapsed.TotalSeconds;
                if (seconds <= 0)
                    return;

                var speed = bytes / seconds;
                var percent = total > 0 ? bytes * 100d / total : 0d;
                var remaining = total > 0 && speed > 1 ? (total - bytes) / speed : -1d;
                var remainingText = remaining >= 0
                    ? TimeSpan.FromSeconds(remaining).ToString(@"hh\:mm\:ss", CultureInfo.InvariantCulture)
                    : I18NManager.Translate("Server.ServerInfo.Unknown");

                Logger.Info(I18NManager.Translate("Server.ServerInfo.DownloadProgress",
                    percent.ToString("F1", CultureInfo.InvariantCulture),
                    FormatSize(bytes),
                    total > 0 ? FormatSize(total) : I18NManager.Translate("Server.ServerInfo.Unknown"),
                    FormatSpeed(speed),
                    remainingText,
                    host));
            },
            OnAttemptFailed = (host, message) =>
            {
                failedCounter++;
                var hasNext = failedCounter < mirrorCount + 1;
                Logger.Warn(I18NManager.Translate(
                    hasNext ? "Server.ServerInfo.DownloadSourceFailed" : "Server.ServerInfo.DownloadSourceFailedAll",
                    host, message));
            },
            OnSlowSource = (host, bytes, total, speed) =>
            {
                // The floor GitHubApi enforces is WindowBytes per WindowSeconds, i.e. 100 KB/s by default.
                Logger.Warn(I18NManager.Translate("Server.ServerInfo.SlowSourceFallback",
                    FormatSpeed(1024 * 1024 / 10d), host, FormatSize(bytes), "10", FormatSpeed(speed)));
            },
            OnSucceeded = (host, isMirror) =>
            {
                if (isMirror)
                    Logger.Warn(I18NManager.Translate("Server.ServerInfo.DownloadedThroughMirror", fileName, host));
                else
                    Logger.Info(I18NManager.Translate("Server.ServerInfo.DownloadedItem", fileName, host));
            }
        };

        return GitHubApi.DownloadAsync(url, destinationPath, options, client);
    }

    private static string FormatSize(long bytes)
        => bytes >= 1024L * 1024
            ? (bytes / 1024d / 1024d).ToString("F1", CultureInfo.InvariantCulture) + " MB"
            : (bytes / 1024d).ToString("F1", CultureInfo.InvariantCulture) + " KB";

    private static string FormatSpeed(double bytesPerSecond)
        => bytesPerSecond >= 1024 * 1024
            ? (bytesPerSecond / 1024 / 1024).ToString("F2", CultureInfo.InvariantCulture) + " MB/s"
            : (bytesPerSecond / 1024).ToString("F0", CultureInfo.InvariantCulture) + " KB/s";

    private static int CopyDirectory(string sourceDirectory, string targetDirectory)
    {
        foreach (var directory in Directory.GetDirectories(sourceDirectory, "*", SearchOption.AllDirectories))
        {
            var relativePath = Path.GetRelativePath(sourceDirectory, directory);
            Directory.CreateDirectory(Path.Combine(targetDirectory, relativePath));
        }

        var copied = 0;
        foreach (var file in Directory.GetFiles(sourceDirectory, "*", SearchOption.AllDirectories))
        {
            var relativePath = Path.GetRelativePath(sourceDirectory, file);
            var destinationPath = Path.Combine(targetDirectory, relativePath);
            Directory.CreateDirectory(Path.GetDirectoryName(destinationPath)!);
            File.Copy(file, destinationPath, overwrite: true);
            copied++;
        }

        return copied;
    }

    private static void VerifySha256(string packagePath, string checksumPath)
    {
        var expected = File.ReadAllText(checksumPath).Split(' ', StringSplitOptions.RemoveEmptyEntries)[0].Trim();
        var actual = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(packagePath)))
            .ToLowerInvariant();

        if (!string.Equals(expected, actual, StringComparison.OrdinalIgnoreCase))
            throw new InvalidDataException("Downloaded update package checksum does not match the release checksum.");
    }
}
